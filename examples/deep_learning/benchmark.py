#!/usr/bin/env python3
"""Benchmark a custom ``KerasModel`` forecaster through ``Experiment``.

Runs the full TSbench generate-and-benchmark lifecycle on the user-defined
``MLPForecaster`` (see ``models.py``) against a *known* ARMA data generating process:

    ARMA(2, 1)   (known DGP)        -> generate a synthetic series
    MLPForecaster    (Keras forecaster) -> train on a prefix, forecast the held-out tail
    Experiment                      -> orchestrate the stages, score mae/rmse

The point: because ``KerasModel.forecast`` honors the ``forecast(T)`` contract
(iterated one-step-ahead), a deep-learning model drops into ``Experiment`` exactly
like ARMA or GARCH — no TSbench internals are touched.

Requires the ``keras`` extra::

    python -m pip install -e .[keras]
    python examples/deep_learning/benchmark.py
"""

from __future__ import annotations

import numpy as np
from numpy.random import PCG64, Generator

from TSbench import TSmodels
from TSbench.experiment import Experiment, ExperimentConfig, General, Output, Stage
from TSbench.metrics import mae, rmse

from models import MLPForecaster  # the reusable forecaster defined next to this script


def main() -> None:
    """Benchmark a custom Keras forecaster against a known ARMA DGP."""
    total = 2000      # length generated by the DGP
    train_end = 1600  # train on [0:train_end], forecast the held-out rest
    horizon = total - train_end

    # Known DGP: an ARMA(2, 1) process whose synthetic series we benchmark on.
    dgp = TSmodels.ARMA(
        p=2,
        q=1,
        ar=np.array([0.75, -0.25]),
        ma=np.array([0.3]),
        variance=0.5,
        rg=Generator(PCG64(7)),
        dim_label=["y"],
        feature_label=["value"],
    )

    # The user's Keras forecaster. Its ``dim_label``/``feature_label`` must match
    # the DGP's ("y" / "value") so the forecast lands on the same (timestamp, dim)
    # rows as the ground truth and Experiment can pair ``value_MLPForecaster`` against
    # ``value``.
    mlp = MLPForecaster(
        window=8,
        units=32,
        epochs=20,
        batch_size=64,
        device="cpu",
        rg=Generator(PCG64(0)),
        dim_label=["y"],
        feature_label=["value"],
    )

    config = ExperimentConfig(
        general=General(data_path="data/keras_experiment/", n_jobs=1),
        generate=Stage(models=[dgp], params={"N": total}),
        train=Stage(models=[mlp], input_loaders_params={"end_index": train_end}),
        forecast=Stage(
            models=[mlp],
            params={"T": horizon},
            input_loaders_params={"end_index": train_end},
        ),
        output=Output(metrics=[mae, rmse]),
    )

    experiment = Experiment(config)
    experiment.run()

    print(
        f"--- MLPForecaster benchmarked on ARMA(2,1) via Experiment "
        f"(train_end={train_end}, horizon={horizon}) ---"
    )
    for ID, model_scores in experiment.results.items():
        for model_name, scores in model_scores.items():
            pretty = "  ".join(f"{k}={v:.4f}" for k, v in scores.items())
            print(f"  {ID} / {model_name}: {pretty}")


if __name__ == "__main__":
    main()
